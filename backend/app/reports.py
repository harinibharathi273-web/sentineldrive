"""Printable repair work order (PDF) for one pothole site."""

import time
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import Image, KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .config import MEDIA_DIR

INK = colors.HexColor("#1c2124")
MUTED = colors.HexColor("#5e676b")
LINE = colors.HexColor("#d5d9d3")
FILL = colors.HexColor("#f1f3ef")
BLUE = colors.HexColor("#1d4e89")
SEV = {"high": colors.HexColor("#b3261e"), "medium": colors.HexColor("#a15c00"), "low": colors.HexColor("#3b6e3b")}

BASE = ParagraphStyle("base", fontName="Helvetica", fontSize=9, leading=12.5, textColor=INK)
SMALL = ParagraphStyle("small", parent=BASE, fontSize=7.5, leading=10, textColor=MUTED)
LABEL = ParagraphStyle("label", parent=BASE, fontSize=7.5, leading=10, textColor=MUTED)
H1 = ParagraphStyle("h1", parent=BASE, fontName="Helvetica-Bold", fontSize=17, leading=21)
H2 = ParagraphStyle("h2", parent=BASE, fontName="Helvetica-Bold", fontSize=10.5, leading=14, spaceBefore=10, spaceAfter=5)
RIGHT = ParagraphStyle("right", parent=BASE, alignment=TA_RIGHT)


def _money(v, cur):
    return f"{cur} {v:,.2f}"


def _date(ms):
    return time.strftime("%d %b %Y, %H:%M", time.localtime(ms / 1000))


def _kv_table(rows, widths):
    t = Table([[Paragraph(k, LABEL), Paragraph(v, BASE)] for k, v in rows], colWidths=widths, hAlign="LEFT")
    t.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 0), (-1, -1), 2),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
            ]
        )
    )
    return t


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(MUTED)
    canvas.drawString(18 * mm, 10 * mm, f"Generated by SentinelDrive on {time.strftime('%d %b %Y %H:%M')}")
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def work_order_pdf(site, rate_card):
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=18 * mm,
        title=f"Work order {site['id']}", author="SentinelDrive",
    )
    W = A4[0] - 36 * mm
    est = site.get("estimate") or {}
    cur = est.get("currency", rate_card.get("currency", "INR"))
    addr = site.get("address") or {}
    jur = site.get("jurisdiction") or {}
    authority = rate_card.get("authority") or jur.get("authority") or "Road maintenance department"
    sev = site.get("severity", "low")
    el = []

    # Header band
    head = Table(
        [
            [
                Paragraph(f"<font color='#5e676b'>{authority}</font>", BASE),
                Paragraph(f"<font color='#5e676b'>Work order</font><br/><b>WO-{site['id']}</b>", RIGHT),
            ],
            [Paragraph("Pothole repair work order", H1), Paragraph(f"Issued {_date(time.time() * 1000)}", RIGHT)],
        ],
        colWidths=[W * 0.68, W * 0.32], hAlign="LEFT",
    )
    head.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "BOTTOM"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ("LINEBELOW", (0, 1), (-1, 1), 1.2, INK),
                ("BOTTOMPADDING", (0, 1), (-1, 1), 8),
            ]
        )
    )
    el += [head, Spacer(1, 8)]

    # Summary strip
    sev_txt = f"<font color='{SEV[sev].hexval().replace('0x', '#')}'><b>{sev.capitalize()}</b></font>"
    strip = Table(
        [
            [Paragraph("Severity", LABEL), Paragraph("Priority", LABEL), Paragraph("Potholes at site", LABEL),
             Paragraph("Reports", LABEL), Paragraph("Estimated cost", LABEL)],
            [Paragraph(sev_txt, BASE), Paragraph(f"<b>{site.get('priority', '-')}</b> / 100", BASE),
             Paragraph(f"<b>{site.get('count', 0)}</b>", BASE), Paragraph(f"<b>{site.get('reports', 1)}</b>", BASE),
             Paragraph(f"<b>{_money(est.get('total', 0), cur)}</b>", BASE)],
        ],
        colWidths=[W / 5] * 5, hAlign="LEFT",
    )
    strip.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), FILL),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, 0), 6),
                ("BOTTOMPADDING", (0, -1), (-1, -1), 7),
            ]
        )
    )
    el += [strip, Spacer(1, 4)]

    # Location
    el.append(Paragraph("Location", H2))
    if site.get("lat") is not None:
        coords = f"{site['lat']:.6f}, {site['lng']:.6f}"
        maps = f"https://www.google.com/maps?q={site['lat']:.6f},{site['lng']:.6f}"
        loc_rows = [
            ("Address", addr.get("display_name") or "Address lookup unavailable — use coordinates"),
            ("Ward / locality", jur.get("ward") or "—"),
            ("Coordinates", f"{coords} &nbsp; <link href='{maps}' color='#1d4e89'>Open in Google Maps</link>"),
            ("Location source", {"device": "Phone GPS", "photo-exif": "Photo metadata (EXIF)",
                                 "set-on-map": "Set manually on map"}.get(site.get("gps_source"), site.get("gps_source") or "—")
             + (f", accuracy ±{site['gps_accuracy_m']:.0f} m" if site.get("gps_accuracy_m") else "")),
        ]
    else:
        loc_rows = [("Coordinates", "Not recorded. Set the location on the map before dispatching a crew.")]
    el.append(_kv_table(loc_rows, [32 * mm, W - 32 * mm]))

    # Evidence + measurements side by side
    el.append(Paragraph("Survey", H2))
    img_flow = Paragraph("No photo on file.", SMALL)
    ev = (site.get("evidence") or [])
    if ev:
        rel = ev[-1]["annotated"].replace("/media/", "", 1)
        path = MEDIA_DIR / rel
        if path.exists():
            img = Image(str(path))
            iw, ih = img.imageWidth, img.imageHeight
            target_w = W * 0.5
            img.drawWidth, img.drawHeight = target_w, target_w * ih / iw
            img_flow = img
    rows = [["#", "Area", "Depth", "Volume", "Conf."]]
    for i, d in enumerate(site.get("defects", []), 1):
        rows.append([str(i), f"{d['area_m2']:.2f} sq m", f"{d['depth_m'] * 1000:.0f} mm",
                     f"{d['volume_m3'] * 1000:.1f} L", f"{d['confidence'] * 100:.0f}%"])
    rows.append(["", f"{site.get('area_m2', 0):.2f} sq m", f"max {site.get('depth_max_m', 0) * 1000:.0f} mm",
                 f"{site.get('volume_m3', 0) * 1000:.1f} L", ""])
    mt = Table(rows, colWidths=[6 * mm, 19 * mm, 19 * mm, 17 * mm, 12 * mm])
    mt.setStyle(
        TableStyle(
            [
                ("FONT", (0, 0), (-1, -1), "Helvetica", 8),
                ("FONT", (0, 0), (-1, 0), "Helvetica", 7),
                ("TEXTCOLOR", (0, 0), (-1, 0), MUTED),
                ("FONT", (0, -1), (-1, -1), "Helvetica-Bold", 8),
                ("LINEBELOW", (0, 0), (-1, 0), 0.6, LINE),
                ("LINEABOVE", (0, -1), (-1, -1), 0.6, INK),
                ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
                ("LEFTPADDING", (0, 0), (-1, -1), 2),
                ("RIGHTPADDING", (0, 0), (-1, -1), 2),
            ]
        )
    )
    detector = (site.get("detector") or {}).get("label", "—")
    method = Paragraph(
        f"Detected by: {detector}.<br/>{site.get('measurement_method', '')} "
        "Dimensions are estimates from one camera; confirm on site before cutting.",
        SMALL,
    )
    side = Table([[mt], [Spacer(1, 6)], [method]], colWidths=[W * 0.46])
    side.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0)]))
    survey = Table([[img_flow, side]], colWidths=[W * 0.54, W * 0.46], hAlign="LEFT")
    survey.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    el.append(survey)

    # Bill of quantities
    boq = [["Item", "Qty", "Unit", f"Rate ({cur})", f"Amount ({cur})"]]
    for ln in est.get("lines", []):
        boq.append([Paragraph(ln["item"], BASE), f"{ln['qty']:,.3f}", ln["unit"].replace("m²", "sq m"), f"{ln['rate']:,.2f}", f"{ln['amount']:,.2f}"])
    boq.append(["", "", "", "Subtotal", f"{est.get('subtotal', 0):,.2f}"])
    boq.append(["", "", "", f"GST {est.get('gst_pct', 0):g}%", f"{est.get('gst', 0):,.2f}"])
    boq.append(["", "", "", "Total", f"{est.get('total', 0):,.2f}"])
    bt = Table(boq, colWidths=[W * 0.46, W * 0.12, W * 0.08, W * 0.16, W * 0.18], repeatRows=1, hAlign="LEFT")
    bt.setStyle(
        TableStyle(
            [
                ("FONT", (0, 0), (-1, -1), "Helvetica", 8.5),
                ("FONT", (0, 0), (-1, 0), "Helvetica", 7.5),
                ("TEXTCOLOR", (0, 0), (-1, 0), MUTED),
                ("LINEBELOW", (0, 0), (-1, 0), 0.6, LINE),
                ("LINEBELOW", (0, 1), (-1, -4), 0.3, LINE),
                ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("FONT", (3, -1), (-1, -1), "Helvetica-Bold", 10),
                ("LINEABOVE", (3, -1), (-1, -1), 1, INK),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    el += [KeepTogether([Paragraph("Bill of quantities", H2), bt]),
           Spacer(1, 4), Paragraph(f"Rates: {est.get('rate_card_note') or rate_card.get('source_note', '')}", SMALL)]

    # Scope + sign-off
    scope = [Paragraph("Scope of work", H2), Paragraph(
        "Barricade the work area. Cut the defect to a square or rectangular outline with vertical edges, remove loose "
        "material and water, apply tack coat to the base and edges, place and compact the patching material in layers "
        "until flush with the surrounding surface. Photograph the finished patch and close this work order in "
        "SentinelDrive.", BASE), Spacer(1, 22)]
    g = W * 0.05
    cw = (W - 2 * g) / 3
    sig = Table(
        [["", "", "", "", ""],
         [Paragraph("Inspected by (name, date)", SMALL), "", Paragraph("Approved by (AE / JE)", SMALL), "",
          Paragraph("Work completed (contractor)", SMALL)]],
        colWidths=[cw, g, cw, g, cw], rowHeights=[22, 12], hAlign="LEFT",
    )
    sig.setStyle(TableStyle([("LINEBELOW", (0, 0), (0, 0), 0.6, INK), ("LINEBELOW", (2, 0), (2, 0), 0.6, INK),
                             ("LINEBELOW", (4, 0), (4, 0), 0.6, INK), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                             ("RIGHTPADDING", (0, 0), (-1, -1), 0)]))
    el.append(KeepTogether(scope + [sig]))

    hist = site.get("history") or []
    if hist:
        el.append(Paragraph("History", H2))
        el.append(_kv_table([(_date(h["ts"]), f"{h['status'].capitalize()}. {h.get('note') or ''}") for h in hist[-8:]],
                            [32 * mm, W - 32 * mm]))

    doc.build(el, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
